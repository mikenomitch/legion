//! Addressing a TAP-wired guest's NIC (gated plan §6.7; docs
//! task-runtime-sandbox.md, "Addressing").
//!
//! Legion leases every TAP guest an address from its bridge's pool. At boot
//! the kernel applies it from the `ip=` command line. After a restore or a
//! fork the guest wakes up with whatever address the captured guest had, so
//! the resume handler re-addresses `eth0` from the identity disk: flush its
//! IPv4 addresses (a static IP from the image, an old DHCP lease, the
//! origin's address in a fork), bounce the link (which empties the neighbor
//! table), add the new address and default route, and rewrite
//! `/etc/resolv.conf`.
//!
//! This talks rtnetlink directly, so an image needs no `ip` tool: the same
//! reason the agent is a static binary.

use std::net::Ipv4Addr;

use anyhow::{bail, Context, Result};

use crate::identity::GuestAddr;

/// The guest's one NIC.
pub const GUEST_NIC: &str = "eth0";

/// A [`GuestAddr`] with its fields parsed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedAddr {
    pub address: Ipv4Addr,
    pub prefix: u8,
    pub gateway: Option<Ipv4Addr>,
    pub dns: Vec<Ipv4Addr>,
}

/// Parse and check a leased address before touching the NIC, so a bad
/// identity never leaves the guest half re-addressed.
pub fn parse(addr: &GuestAddr) -> Result<ParsedAddr> {
    let address: Ipv4Addr = addr
        .address
        .parse()
        .with_context(|| format!("guest address {:?} is not IPv4", addr.address))?;
    if addr.prefix == 0 || addr.prefix > 32 {
        bail!("guest address prefix /{} is out of range", addr.prefix);
    }
    let gateway = addr
        .gateway
        .as_deref()
        .map(|gateway| {
            gateway
                .parse::<Ipv4Addr>()
                .with_context(|| format!("gateway {gateway:?} is not IPv4"))
        })
        .transpose()?;
    let dns = addr
        .dns
        .iter()
        .map(|server| {
            server
                .parse::<Ipv4Addr>()
                .with_context(|| format!("resolver {server:?} is not IPv4"))
        })
        .collect::<Result<Vec<_>>>()?;
    Ok(ParsedAddr {
        address,
        prefix: addr.prefix,
        gateway,
        dns,
    })
}

/// `/etc/resolv.conf` for a TAP guest's leased resolvers.
pub fn resolv_conf(dns: &[Ipv4Addr]) -> String {
    let mut out = String::from("# Generated by Legion from the bridge's sandbox pool.\n");
    for server in dns {
        out.push_str(&format!("nameserver {server}\n"));
    }
    out
}

/// A colon-separated MAC (`02:4c:00:00:00:09`) as bytes.
pub fn parse_mac(mac: &str) -> Result<[u8; 6]> {
    let parts: Vec<&str> = mac.split(':').collect();
    if parts.len() != 6 {
        bail!("MAC {mac:?} does not have six octets");
    }
    let mut out = [0u8; 6];
    for (slot, part) in out.iter_mut().zip(parts) {
        *slot = u8::from_str_radix(part, 16).with_context(|| format!("MAC {mac:?} is not hex"))?;
    }
    Ok(out)
}

