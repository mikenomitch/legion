#[cfg(target_os = "linux")]
mod linux {
    use std::net::Ipv4Addr;
    use std::os::fd::{AsRawFd, FromRawFd, OwnedFd};

    use anyhow::{bail, Context, Result};

    use super::ParsedAddr;

    // rtnetlink ABI constants (linux/rtnetlink.h, linux/netlink.h,
    // linux/if_addr.h). Stable kernel ABI; spelled out rather than taken
    // from `libc`, which does not export every one on every target.
    const NETLINK_ROUTE: libc::c_int = 0;
    const RTM_NEWLINK: u16 = 16;
    const RTM_NEWADDR: u16 = 20;
    const RTM_DELADDR: u16 = 21;
    const RTM_GETADDR: u16 = 22;
    const RTM_NEWROUTE: u16 = 24;
    const NLM_F_REQUEST: u16 = 0x1;
    const NLM_F_ACK: u16 = 0x4;
    const NLM_F_REPLACE: u16 = 0x100;
    const NLM_F_CREATE: u16 = 0x400;
    const NLM_F_DUMP: u16 = 0x300;
    const NLMSG_ERROR: u16 = 2;
    const NLMSG_DONE: u16 = 3;
    const NLMSG_HDRLEN: usize = 16;
    const IFA_ADDRESS: u16 = 1;
    const IFA_LOCAL: u16 = 2;
    const IFLA_ADDRESS: u16 = 1;
    const RTA_OIF: u16 = 4;
    const RTA_GATEWAY: u16 = 5;
    const RT_TABLE_MAIN: u8 = 254;
    const RTPROT_BOOT: u8 = 3;
    const RT_SCOPE_UNIVERSE: u8 = 0;
    const RTN_UNICAST: u8 = 1;
    const IFF_UP: u32 = 0x1;

    fn align4(n: usize) -> usize {
        (n + 3) & !3
    }

    /// One rtnetlink request being built.
    struct Message {
        buf: Vec<u8>,
    }

    impl Message {
        fn new(kind: u16, flags: u16, body: &[u8]) -> Self {
            let mut buf = vec![0u8; NLMSG_HDRLEN];
            buf[4..6].copy_from_slice(&kind.to_ne_bytes());
            buf[6..8].copy_from_slice(&flags.to_ne_bytes());
            buf.extend_from_slice(body);
            buf.resize(align4(buf.len()), 0);
            Message { buf }
        }

        fn attr(mut self, kind: u16, data: &[u8]) -> Self {
            let len = (4 + data.len()) as u16;
            self.buf.extend_from_slice(&len.to_ne_bytes());
            self.buf.extend_from_slice(&kind.to_ne_bytes());
            self.buf.extend_from_slice(data);
            self.buf.resize(align4(self.buf.len()), 0);
            self
        }

        fn finish(mut self, seq: u32) -> Vec<u8> {
            let len = self.buf.len() as u32;
            self.buf[0..4].copy_from_slice(&len.to_ne_bytes());
            self.buf[8..12].copy_from_slice(&seq.to_ne_bytes());
            self.buf
        }
    }

    /// `struct ifaddrmsg`.
    fn ifaddrmsg(prefix: u8, index: u32) -> [u8; 8] {
        let mut body = [0u8; 8];
        body[0] = libc::AF_INET as u8;
        body[1] = prefix;
        body[3] = RT_SCOPE_UNIVERSE;
        body[4..8].copy_from_slice(&index.to_ne_bytes());
        body
    }

    /// `struct ifinfomsg` changing only the up flag.
    fn ifinfomsg(index: u32, up: bool) -> [u8; 16] {
        let mut body = [0u8; 16];
        body[0] = libc::AF_UNSPEC as u8;
        body[4..8].copy_from_slice(&(index as i32).to_ne_bytes());
        body[8..12].copy_from_slice(&(if up { IFF_UP } else { 0 }).to_ne_bytes());
        body[12..16].copy_from_slice(&IFF_UP.to_ne_bytes());
        body
    }

    struct Netlink {
        fd: OwnedFd,
        seq: u32,
    }

    impl Netlink {
        fn open() -> Result<Self> {
            // SAFETY: socket(2) with constant arguments; the descriptor is
            // owned immediately.
            let fd = unsafe {
                libc::socket(
                    libc::AF_NETLINK,
                    libc::SOCK_RAW | libc::SOCK_CLOEXEC,
                    NETLINK_ROUTE,
                )
            };
            if fd < 0 {
                return Err(std::io::Error::last_os_error()).context("open rtnetlink");
            }
            // SAFETY: `fd` was just returned by socket(2) and is not owned
            // elsewhere.
            let fd = unsafe { OwnedFd::from_raw_fd(fd) };
            // SAFETY: a zeroed sockaddr_nl with the family set binds an
            // auto-assigned port; the length is the struct's size.
            let rc = unsafe {
                let mut addr: libc::sockaddr_nl = std::mem::zeroed();
                addr.nl_family = libc::AF_NETLINK as libc::sa_family_t;
                libc::bind(
                    fd.as_raw_fd(),
                    &addr as *const libc::sockaddr_nl as *const libc::sockaddr,
                    std::mem::size_of::<libc::sockaddr_nl>() as libc::socklen_t,
                )
            };
            if rc != 0 {
                return Err(std::io::Error::last_os_error()).context("bind rtnetlink");
            }
            Ok(Netlink { fd, seq: 0 })
        }

        fn send(&mut self, message: Message) -> Result<u32> {
            self.seq += 1;
            let buf = message.finish(self.seq);
            // SAFETY: a valid buffer and its length on an owned socket.
            let sent =
                unsafe { libc::send(self.fd.as_raw_fd(), buf.as_ptr().cast(), buf.len(), 0) };
            if sent < 0 {
                return Err(std::io::Error::last_os_error()).context("send rtnetlink request");
            }
            Ok(self.seq)
        }

        /// Read replies to `seq` until its ACK (or DONE, for a dump),
        /// returning the data messages' (type, payload) in order.
        fn replies(&mut self, seq: u32) -> Result<Vec<(u16, Vec<u8>)>> {
            let mut out = Vec::new();
            let mut buf = vec![0u8; 64 * 1024];
            loop {
                // SAFETY: a valid buffer and its length on an owned socket.
                let read = unsafe {
                    libc::recv(self.fd.as_raw_fd(), buf.as_mut_ptr().cast(), buf.len(), 0)
                };
                if read < 0 {
                    return Err(std::io::Error::last_os_error()).context("read rtnetlink reply");
                }
                let mut at = 0usize;
                let read = read as usize;
                while at + NLMSG_HDRLEN <= read {
                    let len =
                        u32::from_ne_bytes(buf[at..at + 4].try_into().expect("4 bytes")) as usize;
                    if len < NLMSG_HDRLEN || at + len > read {
                        bail!("malformed rtnetlink reply");
                    }
                    let kind = u16::from_ne_bytes(buf[at + 4..at + 6].try_into().expect("2"));
                    let reply_seq =
                        u32::from_ne_bytes(buf[at + 8..at + 12].try_into().expect("4 bytes"));
                    let payload = &buf[at + NLMSG_HDRLEN..at + len];
                    at += align4(len);
                    if reply_seq != seq {
                        continue;
                    }
                    match kind {
                        NLMSG_DONE => return Ok(out),
                        NLMSG_ERROR => {
                            let code = i32::from_ne_bytes(
                                payload.get(0..4).context("short error")?.try_into()?,
                            );
                            if code == 0 {
                                return Ok(out);
                            }
                            return Err(std::io::Error::from_raw_os_error(-code).into());
                        }
                        other => out.push((other, payload.to_vec())),
                    }
                }
            }
        }

        fn request(&mut self, message: Message) -> Result<()> {
            let seq = self.send(message)?;
            self.replies(seq).map(|_| ())
        }
    }

    fn ifindex(name: &str) -> Result<u32> {
        let cname = std::ffi::CString::new(name)?;
        // SAFETY: a NUL-terminated name.
        let index = unsafe { libc::if_nametoindex(cname.as_ptr()) };
        if index == 0 {
            bail!("the guest has no network interface {name}");
        }
        Ok(index)
    }

    fn set_link_up(link: &mut Netlink, index: u32, up: bool) -> Result<()> {
        link.request(Message::new(
            RTM_NEWLINK,
            NLM_F_REQUEST | NLM_F_ACK,
            &ifinfomsg(index, up),
        ))
        .with_context(|| format!("set the link {}", if up { "up" } else { "down" }))
    }

    /// The IPv4 addresses on interface `index`, with their prefix lengths.
    fn addresses(link: &mut Netlink, index: u32) -> Result<Vec<(Ipv4Addr, u8)>> {
        let seq = link.send(Message::new(
            RTM_GETADDR,
            NLM_F_REQUEST | NLM_F_DUMP,
            &ifaddrmsg(0, 0),
        ))?;
        let mut out = Vec::new();
        for (kind, payload) in link.replies(seq)? {
            if kind != RTM_NEWADDR || payload.len() < 8 {
                continue;
            }
            let family = payload[0];
            let prefix = payload[1];
            let on = u32::from_ne_bytes(payload[4..8].try_into()?);
            if family != libc::AF_INET as u8 || on != index {
                continue;
            }
            // Walk the attributes for IFA_LOCAL (else IFA_ADDRESS).
            let mut at = 8usize;
            let (mut local, mut address) = (None, None);
            while at + 4 <= payload.len() {
                let len = u16::from_ne_bytes(payload[at..at + 2].try_into()?) as usize;
                let kind = u16::from_ne_bytes(payload[at + 2..at + 4].try_into()?);
                if len < 4 || at + len > payload.len() {
                    break;
                }
                let data = &payload[at + 4..at + len];
                if data.len() == 4 {
                    let ip = Ipv4Addr::new(data[0], data[1], data[2], data[3]);
                    match kind {
                        IFA_LOCAL => local = Some(ip),
                        IFA_ADDRESS => address = Some(ip),
                        _ => {}
                    }
                }
                at += align4(len);
            }
            if let Some(ip) = local.or(address) {
                out.push((ip, prefix));
            }
        }
        Ok(out)
    }

    /// Give `ifname` the MAC `mac`. The link bounces, so peers relearn it.
    pub fn set_mac(ifname: &str, mac: [u8; 6]) -> Result<()> {
        let index = ifindex(ifname)?;
        let mut link = Netlink::open()?;
        set_link_up(&mut link, index, false)?;
        let changed = link.request(
            Message::new(
                RTM_NEWLINK,
                NLM_F_REQUEST | NLM_F_ACK,
                &ifinfomsg(index, false),
            )
            .attr(IFLA_ADDRESS, &mac),
        );
        set_link_up(&mut link, index, true)?;
        changed.context("set the MAC address")
    }

    /// Re-address `ifname`: drop every IPv4 address it has, bounce the link
    /// (which empties its neighbor table), then add `addr` and, when it has
    /// one, the default route through its gateway.
    pub fn apply(ifname: &str, addr: &ParsedAddr) -> Result<()> {
        let index = ifindex(ifname)?;
        let mut link = Netlink::open()?;
        for (old, prefix) in addresses(&mut link, index)? {
            link.request(
                Message::new(
                    RTM_DELADDR,
                    NLM_F_REQUEST | NLM_F_ACK,
                    &ifaddrmsg(prefix, index),
                )
                .attr(IFA_LOCAL, &old.octets()),
            )
            .with_context(|| format!("remove the old address {old}/{prefix}"))?;
        }
        set_link_up(&mut link, index, false)?;
        set_link_up(&mut link, index, true)?;
        link.request(
            Message::new(
                RTM_NEWADDR,
                NLM_F_REQUEST | NLM_F_ACK | NLM_F_CREATE | NLM_F_REPLACE,
                &ifaddrmsg(addr.prefix, index),
            )
            .attr(IFA_LOCAL, &addr.address.octets())
            .attr(IFA_ADDRESS, &addr.address.octets()),
        )
        .with_context(|| format!("add {}/{}", addr.address, addr.prefix))?;
        if let Some(gateway) = addr.gateway {
            // struct rtmsg: a default (dst_len 0) unicast route in main.
            let rtmsg = [
                libc::AF_INET as u8,
                0,
                0,
                0,
                RT_TABLE_MAIN,
                RTPROT_BOOT,
                RT_SCOPE_UNIVERSE,
                RTN_UNICAST,
                0,
                0,
                0,
                0,
            ];
            link.request(
                Message::new(
                    RTM_NEWROUTE,
                    NLM_F_REQUEST | NLM_F_ACK | NLM_F_CREATE | NLM_F_REPLACE,
                    &rtmsg,
                )
                .attr(RTA_GATEWAY, &gateway.octets())
                .attr(RTA_OIF, &index.to_ne_bytes()),
            )
            .with_context(|| format!("add the default route via {gateway}"))?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_leased_address_parses_or_is_refused_before_touching_the_nic() {
        let addr = GuestAddr {
            address: "10.88.128.7".into(),
            prefix: 16,
            gateway: Some("10.88.0.1".into()),
            dns: vec!["10.88.0.1".into(), "1.1.1.1".into()],
            bridge: "br0".into(),
        };
        let parsed = parse(&addr).unwrap();
        assert_eq!(parsed.address, Ipv4Addr::new(10, 88, 128, 7));
        assert_eq!(parsed.gateway, Some(Ipv4Addr::new(10, 88, 0, 1)));
        assert_eq!(
            resolv_conf(&parsed.dns),
            "# Generated by Legion from the bridge's sandbox pool.\nnameserver 10.88.0.1\n\
             nameserver 1.1.1.1\n"
        );
        for bad in [
            GuestAddr {
                address: "fe80::1".into(),
                ..addr.clone()
            },
            GuestAddr {
                prefix: 33,
                ..addr.clone()
            },
            GuestAddr {
                gateway: Some("gw".into()),
                ..addr.clone()
            },
        ] {
            assert!(parse(&bad).is_err(), "{bad:?}");
        }
        assert_eq!(
            parse_mac("02:4c:00:00:00:09").unwrap(),
            [2, 0x4c, 0, 0, 0, 9]
        );
        assert!(parse_mac("02:4c:00").is_err());
    }

    /// The real thing, in a throwaway network namespace: an `eth0` that
    /// already has an address (the origin's, in a fork) ends with exactly
    /// the leased one and a default route through the gateway. Needs root
    /// (to unshare a network namespace) and the `ip` tool to set up and
    /// inspect, so it skips where it cannot run.
    #[cfg(target_os = "linux")]
    #[test]
    fn a_restore_re_addresses_eth0_through_netlink() {
        let outcome = std::thread::spawn(|| -> Result<Option<String>> {
            // SAFETY: unshare(2) affects only this thread's network namespace.
            if unsafe { libc::unshare(libc::CLONE_NEWNET) } != 0 {
                return Ok(None);
            }
            let ip = |args: &[&str]| -> Result<String> {
                let output = std::process::Command::new("ip").args(args).output()?;
                if !output.status.success() {
                    bail!(
                        "ip {}: {}",
                        args.join(" "),
                        String::from_utf8_lossy(&output.stderr)
                    );
                }
                Ok(String::from_utf8_lossy(&output.stdout).into_owned())
            };
            // A veth pair where the kernel has it (a guest's NIC has a
            // peer too), else a dummy link.
            if ip(&[
                "link", "add", "eth0", "type", "veth", "peer", "name", "eth0p",
            ])
            .is_ok()
            {
                ip(&["link", "set", "eth0p", "up"])?;
            } else if ip(&["link", "add", "eth0", "type", "dummy"]).is_err() {
                return Ok(None);
            }
            ip(&["addr", "add", "10.88.128.2/16", "dev", "eth0"])?;
            ip(&["link", "set", "eth0", "up"])?;
            set_mac("eth0", parse_mac("02:4c:00:00:00:09")?)?;
            apply(
                "eth0",
                &parse(&GuestAddr {
                    address: "10.88.128.7".into(),
                    prefix: 16,
                    gateway: Some("10.88.0.1".into()),
                    dns: Vec::new(),
                    bridge: "br0".into(),
                })?,
            )?;
            let addrs = ip(&["-4", "-o", "addr", "show", "dev", "eth0"])?;
            let routes = ip(&["-4", "route", "show", "default"])?;
            let link = ip(&["-o", "link", "show", "dev", "eth0"])?;
            Ok(Some(format!("{addrs}\n{routes}\n{link}")))
        })
        .join()
        .expect("netns thread");
        let Some(state) = outcome.unwrap() else {
            eprintln!("skipped: needs root and the ip tool to make a network namespace");
            return;
        };
        assert!(state.contains("10.88.128.7/16"), "{state}");
        assert!(
            !state.contains("10.88.128.2"),
            "the old address is gone: {state}"
        );
        assert!(state.contains("default via 10.88.0.1 dev eth0"), "{state}");
        assert!(state.contains("02:4c:00:00:00:09"), "{state}");
    }
}
