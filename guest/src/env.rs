//! The env files a sandbox guest sources: `/legion/env` at boot (written by
//! the worker into the root disk) and `/legion/resume.env` after a restore
//! (written by the resume handler). One renderer, so both are the same
//! shape and quote the same way.

use std::collections::BTreeMap;

/// POSIX single-quote escaping: wrap in `'…'` and close/reopen around any
/// embedded quote. Safe for arbitrary bytes, including newlines.
pub fn sh_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

/// `export KEY='value'` lines, sourced by the guest init. Values may be
/// secrets (KV injection, identity tokens), so this content is never logged.
pub fn render_env_file(env: &BTreeMap<String, String>) -> String {
    let mut out =
        String::from("# Generated by Legion (sandbox task runtime). Sourced by /legion/init.\n");
    for (key, value) in env {
        out.push_str(&format!("export {key}={}\n", sh_quote(value)));
    }
    out
}
