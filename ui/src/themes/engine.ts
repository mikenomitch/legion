// Turns a DesignTheme into CSS variables (plus the studio's fine-tuning
// rules) and applies it to the page. Pure string building apart from
// `applyTheme`, so the studio's "Copy CSS" export uses the same code.
import { RADIUS_SCALES, type DesignTheme, type StatusColors, type ThemeColors } from './catalog'
import { hexToRgb, rgbToHex, statusRamp } from './contrast'

const STYLE_ID = 'design-lab-vars'

const triplet = (hex: string) => hexToRgb(hex).join(' ')

const COLOR_VARS: Record<keyof ThemeColors, string> = {
  canvas: '--c-canvas',
  surface: '--c-surface',
  surface2: '--c-surface2',
  line: '--c-line',
  lineStrong: '--c-line-strong',
  ink: '--c-ink',
  muted: '--c-muted',
  faint: '--c-faint',
  accent: '--c-brass',
  accentStrong: '--c-brass-strong',
}

export const colorVars = (colors: Partial<ThemeColors>) =>
  Object.fromEntries(
    (Object.entries(colors) as Array<[keyof ThemeColors, string]>)
      .filter(([, hex]) => Boolean(hex))
      .map(([key, hex]) => [COLOR_VARS[key], triplet(hex)]),
  )

export const statusVars = (status?: StatusColors) => {
  if (!status) return {}
  const vars: Record<string, string> = {}
  for (const [name, hex] of Object.entries(status)) {
    for (const [shade, rgb] of Object.entries(statusRamp(hex))) vars[`--c-${name}-${shade}`] = rgb.join(' ')
  }
  return vars
}

export const tokenVars = (theme: DesignTheme): Record<string, string> => {
  const radius = RADIUS_SCALES[theme.radius]
  return {
    '--font-sans': theme.type.sans,
    '--font-display': theme.type.display,
    '--font-mono': theme.type.mono,
    '--r-sm': radius.sm,
    '--r': radius.r,
    '--r-md': radius.md,
    '--r-lg': radius.lg,
    '--r-xl': radius.xl,
    '--r-2xl': radius['2xl'],
    '--r-full': radius.full,
    ...(theme.shadow ? { '--shadow-card': theme.shadow.card, '--shadow-pop': theme.shadow.pop } : {}),
    ...colorVars(theme.colors),
    ...statusVars(theme.status),
  }
}

const block = (selector: string, decls: Record<string, string | number | undefined>) => {
  const lines = Object.entries(decls)
    .filter(([, value]) => value !== undefined && value !== '')
    .map(([name, value]) => `  ${name}: ${value};`)
  return lines.length ? `${selector} {\n${lines.join('\n')}\n}` : ''
}

// The runtime sheet. `:root[data-design]` outranks index.css's `.dark`
// block; the attribute's value only picks which flourishes (themes.css) apply.
export const themeStylesheet = (theme: DesignTheme) => {
  const root = ':root[data-design]'
  const parts = [block(root, { ...tokenVars(theme), 'color-scheme': theme.mode, 'font-size': theme.baseSize ? `${theme.baseSize}px` : undefined })]
  if (theme.sidebar && Object.keys(theme.sidebar).length) parts.push(block(`${root} #app-sidebar`, colorVars(theme.sidebar)))
  if (theme.title) {
    parts.push(
      block(`${root} [data-ui="page-title"]`, {
        'font-size': theme.title.size ? `${theme.title.size}rem` : undefined,
        'font-weight': theme.title.weight,
        'text-transform': theme.title.transform,
        'letter-spacing': theme.title.tracking !== undefined ? `${theme.title.tracking}em` : undefined,
        'line-height': theme.title.size ? 1.1 : undefined,
      }),
    )
  }
  if (theme.cardBorder !== undefined) {
    parts.push(block(`${root} [data-ui="card"], ${root} [data-ui="stat"]`, { 'border-width': `${theme.cardBorder}px` }))
  }
  // Recursive is one family for sans and mono; the MONO axis makes it mono.
  if (theme.type.mono.includes('Recursive')) {
    parts.push(block(`${root} .font-mono, ${root} code, ${root} pre, ${root} kbd`, { 'font-variation-settings': "'MONO' 1" }))
  }
  return parts.filter(Boolean).join('\n\n')
}

// index.css-ready tokens: what you paste to ship a theme as the default.
export const exportCss = (theme: DesignTheme) => {
  const selector = theme.mode === 'dark' ? '.dark' : ':root'
  const header = [
    `/* ${theme.name} (${theme.mode}) — generated by the Legion theme studio.`,
    ` * Paste into src/index.css (${selector} block). Structural flourishes, if any,`,
    ` * live in src/themes/themes.css under [data-design='${theme.flourishes ?? theme.id}']. */`,
  ].join('\n')
  const decls: Record<string, string | undefined> = { ...tokenVars(theme), 'color-scheme': theme.mode }
  return `${header}\n${block(selector, decls)}\n${theme.sidebar ? `\n${block(`${selector} #app-sidebar`, colorVars(theme.sidebar))}\n` : ''}`
}

export const applyTheme = (theme: DesignTheme | undefined) => {
  const root = document.documentElement
  document.getElementById(STYLE_ID)?.remove()
  if (!theme) {
    delete root.dataset.design
    return
  }
  const style = document.createElement('style')
  style.id = STYLE_ID
  style.textContent = themeStylesheet(theme)
  document.head.appendChild(style)
  root.dataset.design = theme.flourishes ?? theme.id
  // App.tsx reads this key for its light/dark state; each theme is designed
  // for one mode, so keep the app in step with it.
  try {
    localStorage.setItem('ui-theme', theme.mode)
  } catch {
    // storage unavailable
  }
  root.classList.toggle('dark', theme.mode === 'dark')
}

export const normalizeHex = (value: string): string | undefined => {
  const trimmed = value.trim().replace(/^#?/, '#')
  if (/^#[0-9a-f]{6}$/i.test(trimmed)) return trimmed.toLowerCase()
  if (/^#[0-9a-f]{3}$/i.test(trimmed)) return rgbToHex(hexToRgb(trimmed))
  return undefined
}
