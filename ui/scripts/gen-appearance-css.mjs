// Generates src/appearance/palettes.css — the color tokens for every palette
// in src/appearance/palettes.ts, in both modes — so the page can pick its
// colors from attributes on <html> before any script runs.
//
//   npm run gen:appearance      rewrite the file
//   npm run check:appearance    fail if the file is out of date (CI)
//
// Node >= 22.18 strips the TS types.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { DEFAULT_PALETTE, PALETTES } from '../src/appearance/palettes.ts'
import { contrast, hexToRgb, statusRamp } from '../src/themes/contrast.ts'

const OUT = fileURLToPath(new URL('../src/appearance/palettes.css', import.meta.url))

const COLOR_VARS = {
  canvas: '--c-canvas',
  surface: '--c-surface',
  surface2: '--c-surface2',
  line: '--c-line',
  lineStrong: '--c-line-strong',
  ink: '--c-ink',
  muted: '--c-muted',
  faint: '--c-faint',
  accent: '--c-brass',
  accentStrong: '--c-brass-strong',
}

const triplet = (hex) => hexToRgb(hex).join(' ')

// Text on a signal-colored fill (an active nav item): whichever of white or
// near-black reads better on it.
const signalInk = (signal) => (contrast('#ffffff', signal) >= contrast('#0a0a0a', signal) ? '#ffffff' : '#0a0a0a')

const declarations = (spec, mode) => {
  const lines = Object.entries(COLOR_VARS).map(([key, name]) => `${name}: ${triplet(spec.colors[key])};`)
  for (const [status, hex] of Object.entries(spec.status)) {
    for (const [shade, rgb] of Object.entries(statusRamp(hex))) lines.push(`--c-${status}-${shade}: ${rgb.join(' ')};`)
  }
  lines.push(`--c-signal: ${triplet(spec.signal)};`, `--signal-ink: ${signalInk(spec.signal)};`, `color-scheme: ${mode};`)
  return lines.map((line) => `  ${line}`).join('\n')
}

const rule = (selector, spec, mode) => `${selector} {\n${declarations(spec, mode)}\n}`

// The default palette needs no attribute. The others are keyed on
// data-palette, and step aside under [data-design] so the dev-only theme lab's
// own token sheet decides the colors while a lab preset is applied.
const parts = [
  '/* Generated by scripts/gen-appearance-css.mjs from src/appearance/palettes.ts.',
  ' * Do not edit by hand: change palettes.ts and run `npm run gen:appearance`. */',
]
for (const palette of PALETTES) {
  parts.push('', `/* ${palette.name}: ${palette.description} */`)
  if (palette.id === DEFAULT_PALETTE) {
    parts.push(rule(':root', palette.light, 'light'), rule('.dark', palette.dark, 'dark'))
  } else {
    const key = `:not([data-design])[data-palette='${palette.id}']`
    parts.push(rule(`:root${key}`, palette.light, 'light'), rule(`:root.dark${key}`, palette.dark, 'dark'))
  }
}
const css = parts.join('\n') + '\n'

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {}
  if (current !== css) {
    console.error('src/appearance/palettes.css is out of date: run `npm run gen:appearance`.')
    process.exitCode = 1
  } else {
    console.log('src/appearance/palettes.css is up to date.')
  }
} else {
  writeFileSync(OUT, css)
  console.log(`wrote ${OUT}`)
}
